Mesh Primitive::Sphere(int sectorCount, int stackCount, float radius)
{
    std::vector<Vertex>       vertices;
    std::vector<unsigned int> indices;

    const float PI = 3.14159265358979323846f;
    float sectorStep = 2.0f * PI / sectorCount;
    float stackStep = PI / stackCount;

    // 生成顶点
    for (int i = 0; i <= stackCount; ++i)
    {
        float stackAngle = PI / 2.0f - i * stackStep;
        float xy = radius * cosf(stackAngle);
        float z = radius * sinf(stackAngle);

        for (int j = 0; j <= sectorCount; ++j)
        {
            float sectorAngle = j * sectorStep;

            float x = xy * cosf(sectorAngle);
            float y = xy * sinf(sectorAngle);

            Vertex v;
            v.Position = { x, y, z };
            v.Normal = { x / radius, y / radius, z / radius };
            v.TexCoords = { (float)j / sectorCount, (float)i / stackCount };
            v.Tangent = { 0.0f, 0.0f, 0.0f }; // 暂时留空

            vertices.push_back(v);
        }
    }

    // 生成 indices
    int stride = sectorCount + 1;
    for (int i = 0; i < stackCount; ++i)
    {
        for (int j = 0; j < sectorCount; ++j)
        {
            unsigned int k1 = i * stride + j;
            unsigned int k2 = k1 + 1;
            unsigned int k3 = (i + 1) * stride + j;
            unsigned int k4 = k3 + 1;

            if (i != 0)
                indices.insert(indices.end(), { k1, k3, k2 });

            if (i != stackCount - 1)
                indices.insert(indices.end(), { k2, k3, k4 });
        }
    }

    return Mesh(vertices, indices, {}); // 无纹理传空 vector
}